package harness.cli

import ai.koog.agents.core.agent.asMermaidDiagram
import harness.graph.TestGraph
import org.springframework.stereotype.Component
import picocli.CommandLine.Command

@Component
@Command(name = "graph", mixinStandardHelpOptions = true, description = ["Print the test graph as a Mermaid diagram, generated by Koog from the real strategy."])
class GraphCommand(private val graph: TestGraph) : Runnable {

    override fun run() {
        println(graph.strategy().asMermaidDiagram())
    }
}
